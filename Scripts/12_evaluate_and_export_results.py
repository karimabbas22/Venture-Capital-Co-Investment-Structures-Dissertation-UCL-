"""
12_evaluate_and_export_results.py — final evaluation and comparison report.

Aggregates results from all previous scripts into a single report, ordered
to match the dissertation's robustness-first framing:
  1. Overall predictive performance (baseline vs network)
  2. Robustness comparison (perturbation stability — the central contribution)
  3. Temporal network comparison (secondary supporting analysis)
  4. Survival / time-to-event analysis (deprecated — this track (H4) was
     excised from the final dissertation write-up and its generating code
     is not part of this package. This section only appears if
     Data/processed/models/survival/ still has results on disk from an
     earlier run.)
"""

import json
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
from pipeline_core import build_anchor_dates, ENTRY_START, ENTRY_END, T_YEARS

ROOT       = Path(__file__).resolve().parent.parent
DATA       = ROOT / "Data" / "processed"
MODEL_DIR  = DATA / "models" / "T7"
PERT_DIR   = MODEL_DIR / "perturbation"

REPORT_PATH = DATA / "final_T7_analysis_report.md"


def load_json(path):
    if not path.exists():
        print(f"[WARN] Missing: {path}")
        return None
    with open(path) as f:
        return json.load(f)


def load_csv(path):
    if not path.exists():
        print(f"[WARN] Missing: {path}")
        return None
    return pd.read_csv(path)


def main():
    print("\nFinal T=7 analysis report")

    lines = ["# Final T=7 Analysis Report", "",
             "_Auto-generated by `Scripts/12_evaluate_and_export_results.py`._", ""]

    # Sample & outcome framing
    lines += ["## 0. Sample & Outcome Framing", ""]
    deals_path = DATA / "deals.parquet"
    panel_path = DATA / "firms_panel.parquet"
    if deals_path.exists() and panel_path.exists():
        deals = pd.read_parquet(deals_path)
        anchors = build_anchor_dates(deals)
        n_universe = len(anchors)
        n_in_window = len(pd.read_parquet(panel_path))  # authoritative eligible-sample count

        # Four disjoint buckets, computed explicitly rather than by subtraction:
        # inferring the post-window bucket via subtraction would silently
        # absorb the pre-ENTRY_START-but-in-coverage cohort below into
        # "post-window".
        pre_flagged = anchors["pre_window_first_round"]
        not_flagged = anchors.loc[~pre_flagged]
        n_pre_coverage_excl = int(pre_flagged.sum())
        n_before_entry_start_excl = int(
            (not_flagged["first_deal_date"] < ENTRY_START).sum())
        n_post_window_excl = int(
            (not_flagged["first_deal_date"] > ENTRY_END).sum())
        n_in_range = n_universe - n_pre_coverage_excl - n_before_entry_start_excl - n_post_window_excl
        n_dropped_other = n_in_range - n_in_window  # inconsistent-exit / censoring drops

        lines += [
            f"The underlying outcome of interest is exit **timing and type** — a "
            f"time-to-event process (IPO, acquisition/trade sale, liquidation, or "
            f"continued private operation). The T={T_YEARS}yr binary classification "
            f"used throughout this report is a **fixed-horizon benchmark "
            f"operationalization** of that process, chosen for comparability with "
            f"prior graph-ML exit-prediction literature — not the conceptually "
            f"canonical framing (the survival/competing-risks alternative is "
            f"discussed in Section 4 below).",
            "",
            f"- **Total companies in the underlying deal data:** {n_universe:,}",
            f"- **Excluded — true first VC round predates this company's own "
            f"earliest deal record** (effectively pre-2000 coverage, not "
            f"reliably observable at all): "
            f"{n_pre_coverage_excl:,} ({100*n_pre_coverage_excl/n_universe:.1f}%)",
            f"- **Excluded — first VC round {ENTRY_START.year-10}–{ENTRY_START.year-1} "
            f"(before the {ENTRY_START.year}–{ENTRY_END.year} entry window, but with "
            f"a known, in-coverage first-investment date):** "
            f"{n_before_entry_start_excl:,} ({100*n_before_entry_start_excl/n_universe:.1f}%)",
            f"- **Excluded — first VC round {ENTRY_END.year+1}–2024 "
            f"(T={T_YEARS}yr outcome window not yet closed by DATA_END=2024):** "
            f"{n_post_window_excl:,} ({100*n_post_window_excl/n_universe:.1f}%)",
            f"- **Classification sample ({ENTRY_START.year}–{ENTRY_END.year} entry "
            f"cohort):** {n_in_window:,} ({100*n_in_window/n_universe:.1f}%)"
            + (f" — {n_dropped_other:,} further row(s) inside this window dropped "
               f"by `filter_classification_sample` (inconsistent-exit/censoring)."
               if n_dropped_other else "."),
            "",
            f"This sample should be read as the **observability-eligible subsample** "
            f"under the fixed-horizon benchmark, not the full population of US "
            f"VC-backed startups over the study period.",
            "",
        ]
        print(f"  Sample framing: {n_in_window:,}/{n_universe:,} companies "
              f"({100*n_in_window/n_universe:.1f}%) in the classification sample")

    # Overall predictive performance
    lines += ["## 1. Overall Predictive Performance", ""]

    firms_path = DATA / "firms_panel.parquet"
    if firms_path.exists():
        firms = pd.read_parquet(firms_path)
        n_total = len(firms)
        n_exits = int(firms["exit_within_T"].sum())
        lines += [
            "### Dataset overview", "",
            f"- **Total startups:** {n_total:,}",
            f"- **Exits within T=7:** {n_exits:,} ({100*n_exits/n_total:.1f}%)",
            f"- **No exit:** {n_total - n_exits:,} ({100*(n_total-n_exits)/n_total:.1f}%)",
            "",
        ]
        print(f"  Startups: {n_total:,}  Exits: {n_exits:,} ({100*n_exits/n_total:.1f}%)")

    baseline = load_json(MODEL_DIR / "baseline_results.json")
    if baseline:
        lines += ["### Baseline model (no network) — fixed-horizon benchmark", ""]
        lines.append("| Model | ROC-AUC | PR-AUC | F1 | Brier |")
        lines.append("|---|---|---|---|---|")
        for r in sorted(baseline, key=lambda x: -x["roc_auc"]):
            lines.append(f"| {r['model']} | {r['roc_auc']:.4f} | {r['pr_auc']:.4f} | "
                        f"{r['f1']:.4f} | {r['brier']:.4f} |")
        lines.append("")
        best_b = max(baseline, key=lambda x: x["roc_auc"])
        print(f"  Best baseline: {best_b['model']} ROC-AUC={best_b['roc_auc']:.4f}")

    network = load_json(MODEL_DIR / "network_results.json")
    if network:
        lines += ["### Network-augmented model", ""]
        lines.append("| Model | ROC-AUC | PR-AUC | F1 | Brier |")
        lines.append("|---|---|---|---|---|")
        for r in sorted(network, key=lambda x: -x["roc_auc"]):
            lines.append(f"| {r['model']} | {r['roc_auc']:.4f} | {r['pr_auc']:.4f} | "
                        f"{r['f1']:.4f} | {r['brier']:.4f} |")
        lines.append("")

        if baseline:
            lines += ["### Network feature lift", ""]
            net_by_name = {r["model"].replace("_Network", ""): r for r in network}
            for br in sorted(baseline, key=lambda x: -x["roc_auc"]):
                base_name = br["model"].replace("_Baseline", "")
                nr = net_by_name.get(base_name)
                if nr:
                    d_roc = nr["roc_auc"] - br["roc_auc"]
                    lines.append(f"- **{base_name}**: Δ ROC-AUC = {d_roc:+.4f} "
                               f"({br['roc_auc']:.4f} → {nr['roc_auc']:.4f})")
            lines.append("")

    gnn = load_json(MODEL_DIR / "gnn_results.json")
    if gnn:
        lines += ["### Heterogeneous bipartite GNN", "",
                 "_Operates directly on the investor–startup bipartite graph "
                 "(startup and investor nodes, `invests_in` and `co_invests_with` "
                 "edges) via a 2-layer HeteroConv/SAGEConv network, rather than "
                 "graph-derived tabular features._", ""]
        lines.append("| Model | ROC-AUC | PR-AUC | F1 | Brier |")
        lines.append("|---|---|---|---|---|")
        for r in gnn:
            lines.append(f"| {r['model']} | {r['roc_auc']:.4f} | {r['pr_auc']:.4f} | "
                        f"{r['f1']:.4f} | {r['brier']:.4f} |")
        lines.append("")
        if baseline and network:
            best_b = max(baseline, key=lambda x: x["roc_auc"])
            best_n = max(network, key=lambda x: x["roc_auc"])
            gnn_r = gnn[0]
            lines.append(f"- GNN vs. best tabular baseline: Δ ROC-AUC = "
                        f"{gnn_r['roc_auc']-best_b['roc_auc']:+.4f} "
                        f"({best_b['roc_auc']:.4f} → {gnn_r['roc_auc']:.4f})")
            lines.append(f"- GNN vs. best tabular network model: Δ ROC-AUC = "
                        f"{gnn_r['roc_auc']-best_n['roc_auc']:+.4f} "
                        f"({best_n['roc_auc']:.4f} → {gnn_r['roc_auc']:.4f})")
            lines.append("")
        print(f"  GNN: {gnn[0]['model']} ROC-AUC={gnn[0]['roc_auc']:.4f}")

    # Robustness comparison (central contribution)
    lines += ["## 2. Robustness Comparison", "",
             "_Whether the network model's predictions — and any lift over baseline — "
             "survive controlled perturbations of the co-investment graph. This is the "
             "dissertation's central empirical question._",
             "",
             "_Includes both the 5 tabular network models (script 07) and the "
             "heterogeneous bipartite GNN (script 10). **Methodological caveat**: "
             "the GNN's perturbations change message-passing topology only — investor "
             "features are not recomputed post-perturbation, unlike the tabular "
             "protocol, which does recompute centrality features after each "
             "perturbation. GNN-vs-tabular robustness numbers below are therefore "
             "not a like-for-like architecture comparison; within-model trends "
             "(e.g. hub removal vs. random deletion) remain valid for each model "
             "individually._",
             ""]

    wide = load_csv(PERT_DIR / "robustness_summary_wide.csv")
    if wide is not None:
        budget_rows = wide[wide["perturb_type"] != "hub_removal"]
        hub_rows = wide[wide["perturb_type"] == "hub_removal"]

        findings = []
        for ptype in ["random_edge_deletion", "random_edge_addition",
                     "degree_aware_edge_deletion", "edge_rewiring"]:
            sub = budget_rows[budget_rows["perturb_type"] == ptype]
            if sub.empty:
                continue
            max_b = sub["budget"].max()
            at_max = sub[sub["budget"] == max_b]
            worst = at_max.loc[at_max["delta_roc_auc_mean"].idxmin()]
            findings.append(
                f"- At the highest tested budget ({max_b:.1%}) of **{ptype.replace('_',' ')}**, "
                f"the largest AUC degradation is **{worst['model']}** "
                f"(Δ ROC-AUC = {worst['delta_roc_auc_mean']:+.4f} ± {worst['delta_roc_auc_std']:.4f}, "
                f"flip rate = {worst['flip_rate_mean']:.1%}).")

        if not hub_rows.empty:
            worst_hub = hub_rows.loc[hub_rows["delta_roc_auc_mean"].idxmin()]
            lowest_rho = hub_rows.loc[hub_rows["spearman_rho_mean"].idxmin()]
            if worst_hub["delta_roc_auc_mean"] < 0:
                auc_desc = (f"the largest AUC decrease observed under hub removal is "
                           f"**{worst_hub['model']}** at K={int(worst_hub['hub_k'])} "
                           f"(Δ ROC-AUC = {worst_hub['delta_roc_auc_mean']:+.4f})")
            else:
                auc_desc = (f"no model shows an AUC decrease under hub removal — the smallest "
                           f"gain is **{worst_hub['model']}** at K={int(worst_hub['hub_k'])} "
                           f"(Δ ROC-AUC = {worst_hub['delta_roc_auc_mean']:+.4f})")
            findings.append(
                f"- Hub removal: {auc_desc}. Rank stability degrades more visibly than aggregate "
                f"AUC — lowest Spearman ρ is **{lowest_rho['model']}** at K={int(lowest_rho['hub_k'])} "
                f"(ρ = {lowest_rho['spearman_rho_mean']:.4f}), showing hub removal can reshuffle "
                f"*which* startups are flagged even when overall discrimination barely moves.")

        lines += findings + [""]
        lines += ["### Robustness curves", "",
                 "![Robustness grid](models/T7/perturbation/robustness_grid.png)", "",
                 "Full tables: `models/T7/perturbation/robustness_summary_wide.csv` "
                 "(mean ± std over seeds, all metrics) and "
                 "`models/T7/perturbation/by_metric/` (one CSV per metric, budget × model).",
                 ""]
        print(f"  Robustness summary: {len(wide)} aggregated scenarios")
    else:
        lines += ["_Not yet run — see `Scripts/07_run_perturbation_tests.py` and "
                 "`Scripts/11_aggregate_robustness_report.py`._", ""]

    # Temporal network comparison (supporting analysis)
    lines += ["## 3. Temporal Network Comparison (supporting analysis)", ""]
    period_path = DATA / "period_network_comparison.csv"
    if period_path.exists():
        pc = pd.read_csv(period_path)
        keep_cols = [c for c in ["period", "nodes", "edges", "density",
                                 "mean_degree", "mean_clustering"] if c in pc.columns]
        lines.append((pc[keep_cols] if keep_cols else pc).to_markdown(index=False))
        lines.append("")
        print(f"  Period comparison: {len(pc)} periods")
    else:
        lines += ["_Not yet run._", ""]

    # Survival / time-to-event analysis (deprecated)
    lines += ["## 4. Survival / Time-to-Event Analysis (deprecated — excluded from final write-up)", "",
             "_**This track (H4) was excised from the final dissertation** and "
             "its generating code is not part of this package. The section "
             "below only renders if results from an earlier run still exist "
             "on disk — it is not regenerated by the current 01–12 pipeline._",
             "",
             "_Cause-specific Cox proportional-hazards competing-risks models "
             "(exit vs. failure, right-censored otherwise), fit over the full "
             "available panel rather than the T=7yr fixed-horizon benchmark's "
             "observability-eligible subsample. This is the literature-preferred "
             "conceptual framing for VC exit timing (duration-model treatments of "
             "venture-backed company longevity)._",
             "",
             "_**Comparability caveat, stated plainly**: Model A's population "
             "(2000–2024, all entrants) is not the same as the T=7 classification "
             "sample (2010–2017 only), and concordance index (C-index) is not "
             "ROC-AUC — they are not directly numerically comparable, only "
             "loosely analogous (both measure discriminative ranking ability)._",
             ""]
    surv_path = DATA / "models" / "survival" / "survival_results.json"
    surv_data = load_json(surv_path)
    if surv_data:
        lines.append("| Model | Cause | Concordance (val) | Concordance (test) | "
                     "n_test | n_events (test) |")
        lines.append("|---|---|---|---|---|---|")
        for r in surv_data:
            lines.append(f"| {r['feature_set']} | {r['cause']} | "
                        f"{r['val_concordance']:.4f} | {r['test_concordance']:.4f} | "
                        f"{r['n_test']:,} | {r['n_events_test']} |")
        lines.append("")

        low_power = [r for r in surv_data if r["n_events_test"] < 30]
        if low_power:
            lines.append("**Reliability warning**: the following models have "
                         "very few events in the test fold and their concordance "
                         "estimates should not be treated as reliable findings — "
                         "reported for completeness, not as evidence:")
            for r in low_power:
                lines.append(f"- `{r['model_id']}`: only {r['n_events_test']} "
                            f"events in test (n_test={r['n_test']:,}). This "
                            f"reflects genuine rarity of dated failure/bankruptcy "
                            f"status updates in the underlying data, not a "
                            f"modelling error.")
            lines.append("")

        diag_path = DATA / "models" / "survival" / "survival_diagnostics.json"
        diag = load_json(diag_path)
        if diag:
            lines.append("**Proportional-hazards assumption**: checked via "
                         "`CoxPHFitter.check_assumptions()` for each model "
                         "(full diagnostic output in "
                         "`models/survival/survival_diagnostics.json`); some "
                         "covariates in some models show statistically detectable "
                         "non-proportionality (expected at this sample size — "
                         "the test is very sensitive — and reported rather than "
                         "hidden, per this project's standing convention of "
                         "stating limitations plainly).")
            lines.append("")

        lines += ["### Kaplan-Meier: time to exit / failure", "",
                 "![Survival curve](models/survival/survival_km_curve.png)", ""]
        print(f"  Survival models: {len(surv_data)} fitted")
    else:
        lines += ["_Not run in the active pipeline — this track is deprecated "
                 "and its generating code is not part of this package._", ""]

    # Write report
    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.write_text("\n".join(lines))
    print(f"\n  Report written to: {REPORT_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
